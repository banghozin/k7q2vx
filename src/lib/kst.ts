/**
 * 한국 시각으로 본 날짜.
 *
 * 이 사이트를 보는 사람은 한국에 있는데, 다루는 기사와 시세는 미국 것입니다.
 * 시각을 표준시(UTC)로 두면 아홉 시간이 어긋나고, 미국 매체는 미국 오후에
 * 기사를 내므로 그 차이가 **날짜까지** 바꿉니다. 실제로 보관된 기사의 62%가
 * 표준시 날짜와 한국 날짜가 서로 달랐습니다.
 *
 * 한국은 서머타임이 없어 UTC+9 로 고정입니다. 아홉 시간을 더해 자르면 됩니다.
 * `Intl` 을 쓰지 않는 것은 기사마다 한 번씩 부르는 자리이기 때문입니다.
 *
 * **거래일에는 쓰지 마세요.** 일봉의 날짜나 `asOf` 는 미국 거래일이라 여기에
 * 아홉 시간을 더하면 오히려 어긋납니다. 이 함수는 "사람이 겪은 시각" 을
 * 날짜로 바꿀 때만 씁니다.
 */
export function kstDay(iso: string): string {
  const t = new Date(iso).getTime();
  if (Number.isNaN(t)) return iso.slice(0, 10);
  return new Date(t + 9 * 3600000).toISOString().slice(0, 10);
}
